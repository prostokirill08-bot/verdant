def sales_system() -> str:
    return SALES_SYSTEM.format(brand=get_settings().brand_name, prices=price_list_text(), turnaround=TURNAROUND)


def safe_reply(text: str) -> bool:
    """Ответ модели не должен содержать неутверждённых цен и скидок."""
    if not text or len(text) > 1500:
        return False
    if re.search(r"скидк|акци|промокод|бесплатно сделаем все|гарантир\w* рост", text, re.I):
        return False
    for m in re.finditer(r"(\d[\d\s]{2,})\s?(?:₽|руб)", text):
        if int(re.sub(r"\s", "", m.group(1))) not in ALLOWED_PRICES_RUB:
            return False
    return True
